package io.github.jys0615.stayport.application;

/**
 * 검색 응답에 실리는 공급사별 상태.
 *
 * <p>부분 실패를 허용한다는 말은 응답에 "어디까지 받았는지"가 드러나야 한다는 뜻이다.
 * 상품 목록만 주면 클라이언트는 결과가 적은 이유를 알 수 없다.
 */
public enum SupplierStatus {

    /** 물어본 것을 전부 받았다. */
    OK,

    /** 여러 번 나눠 물어봤고 일부만 받았다. 받은 것은 결과에 들어 있다. */
    PARTIAL,

    /** 물어봤지만 아무것도 받지 못했다. */
    FAILED,

    /**
     * 물어볼 것이 없었다 — 이 공급사의 매핑이 아직 없다.
     *
     * <p>{@link #FAILED}와 나누는 이유는 원인이 다르기 때문이다. FAILED는 공급사 쪽 문제이고
     * 이쪽은 우리 동기화가 아직 안 됐다는 뜻이다. 클라이언트가 할 일도 다르다 — 전자는 잠시 후
     * 재시도, 후자는 재시도해도 같다. 첫 실행과 공급사 장애가 겹치면 이 상태가 된다.
     */
    NO_MAPPING
}
